"""
report.py
---------
Generates the PDF verification certificate.

Design decision worth defending in the viva: the report includes the SHA-256 of
the exact file that was examined. Without it, a verification report is
unfalsifiable -- it asserts a verdict about "an image" with no way to prove
which image. With the hash, anyone can recompute it and confirm the report
refers to the file in front of them.

The secret password is never written to the PDF. Only a truncated hash of the
derived key is included, which is enough to confirm two reports used the same
key without leaking the key itself.
"""

from __future__ import annotations

import hashlib
import io
import os
from datetime import datetime

import cv2
import numpy as np
from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.lib.utils import ImageReader
from reportlab.platypus import (Image, Paragraph, SimpleDocTemplate, Spacer,
                                Table, TableStyle)

from utils import file_sha256, timestamp
from watermark import derive_key

VERDICT_COLOURS = {
    "AUTHENTIC": colors.HexColor("#1B7F3B"),
    "TAMPERED": colors.HexColor("#B3261E"),
    "UNVERIFIABLE": colors.HexColor("#A15C00"),
}


def _to_flowable(bgr: np.ndarray, max_w: float, max_h: float = None) -> Image:
    """Convert an OpenCV BGR array into a reportlab Image, preserving aspect ratio.

    Both dimensions must be bounded, not just the width. Fitting to width alone
    means a portrait image taller than roughly 3:1 -- a document scan, a receipt,
    a long screenshot -- is laid out taller than the printable frame, and
    reportlab aborts the entire build with a LayoutError instead of producing a
    report. Constraining the height as well keeps any aspect ratio on the page.
    """
    rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB) if bgr.ndim == 3 else \
        cv2.cvtColor(bgr, cv2.COLOR_GRAY2RGB)
    ok, buf = cv2.imencode(".png", cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR))
    if not ok:
        raise IOError("Could not encode image for the report.")
    stream = io.BytesIO(buf.tobytes())
    h, w = bgr.shape[:2]
    draw_w = min(max_w, w)
    draw_h = draw_w * h / w
    if max_h and draw_h > max_h:
        draw_h = max_h
        draw_w = draw_h * w / h
    return Image(stream, width=draw_w, height=draw_h)


def _key_fingerprint(password: str) -> str:
    """Short, non-reversible identifier for the key used. Never exposes the password."""
    return hashlib.sha256(derive_key(password)).hexdigest()[:16].upper()


def generate_report(output_path: str,
                    result,
                    owner: str,
                    original_image: np.ndarray,
                    overlay_image: np.ndarray,
                    password: str,
                    filename: str = "uploaded_image.png",
                    quality: dict = None,
                    scores: dict = None) -> str:
    """Build the PDF. Returns the path written.

    Parameters
    ----------
    result : detector.DetectionResult
    quality : optional dict from utils.quality_metrics (embedding step only)
    scores  : optional dict from utils.localisation_scores (evaluation runs only)
    """
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)

    doc = SimpleDocTemplate(
        output_path, pagesize=A4,
        leftMargin=18 * mm, rightMargin=18 * mm,
        topMargin=16 * mm, bottomMargin=16 * mm,
        title="Image Authentication Report", author="ImageAuth",
    )

    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=styles["Title"], fontSize=18, spaceAfter=2)
    sub = ParagraphStyle("sub", parent=styles["Normal"], fontSize=9,
                         textColor=colors.grey, alignment=TA_CENTER, spaceAfter=10)
    h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=12, spaceBefore=10,
                        spaceAfter=4, textColor=colors.HexColor("#222222"))
    body = ParagraphStyle("body", parent=styles["Normal"], fontSize=9, leading=12)
    mono = ParagraphStyle("mono", parent=styles["Normal"], fontSize=7.5,
                          fontName="Courier", leading=9)
    verdict_style = ParagraphStyle(
        "verdict", parent=styles["Normal"], fontSize=20, alignment=TA_CENTER,
        spaceBefore=4, spaceAfter=4,
        textColor=VERDICT_COLOURS.get(result.verdict, colors.black),
    )

    content_w = doc.width
    story = []

    story.append(Paragraph("Image Authentication Report", h1))
    story.append(Paragraph(
        "Fragile block-wise watermark verification &mdash; generated by ImageAuth", sub))

    # ---- Verdict banner -------------------------------------------------- #
    banner = Table([[Paragraph(f"<b>{result.verdict}</b>", verdict_style)]],
                   colWidths=[content_w])
    banner.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 1.2,
         VERDICT_COLOURS.get(result.verdict, colors.black)),
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F7F7F7")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(banner)
    story.append(Spacer(1, 4))
    story.append(Paragraph(result.confidence_note, body))

    # ---- Case details ---------------------------------------------------- #
    story.append(Paragraph("Case Details", h2))
    details = [
        ["Claimed owner", owner or "(not supplied)"],
        ["File examined", filename],
        ["Verified on", timestamp()],
        ["Key fingerprint", _key_fingerprint(password)],
        ["Block size", f"{result.block_size} x {result.block_size} px"],
    ]
    story.append(_kv_table(details, content_w))

    story.append(Paragraph("SHA-256 of examined file", h2))
    story.append(Paragraph(file_sha256(original_image), mono))

    # ---- Findings -------------------------------------------------------- #
    story.append(Paragraph("Findings", h2))
    findings = [
        ["Blocks failing authentication", f"{result.tampered_blocks} / {result.total_blocks}"],
        ["Tampered area", f"{result.tampered_percent} %"],
        ["Distinct tampered regions", str(len(result.regions))],
    ]
    story.append(_kv_table(findings, content_w))

    if result.regions:
        story.append(Spacer(1, 6))
        rows = [["Region", "Top-left (x, y)", "Size (w x h) px", "Area (px)"]]
        for i, r in enumerate(result.regions[:12], start=1):
            rows.append([f"R{i}", f"({r['x']}, {r['y']})",
                         f"{r['w']} x {r['h']}", f"{r['area_px']:,}"])
        story.append(_grid_table(rows, content_w))

    # ---- Optional metric blocks ------------------------------------------ #
    if quality:
        story.append(Paragraph("Embedding Quality (imperceptibility)", h2))
        story.append(_grid_table(
            [list(quality.keys()), [str(v) for v in quality.values()]], content_w))

    if scores:
        story.append(Paragraph("Localisation Accuracy vs Ground Truth", h2))
        keys = ["Precision", "Recall", "F1", "Accuracy"]
        story.append(_grid_table(
            [keys, [str(scores.get(k, "-")) for k in keys]], content_w))

    # ---- Visual evidence ------------------------------------------------- #
    story.append(Paragraph("Visual Evidence", h2))
    half = (content_w - 8) / 2
    half_h = doc.height - 40      # leave room for the caption row beneath
    pair = Table(
        [[_to_flowable(original_image, half, half_h),
          _to_flowable(overlay_image, half, half_h)],
         [Paragraph("<b>Examined image</b>", body),
          Paragraph("<b>Tamper map</b> (red = failed blocks)", body)]],
        colWidths=[half + 4, half + 4],
    )
    pair.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("TOPPADDING", (0, 1), (-1, 1), 3),
    ]))
    story.append(pair)

    # ---- Scope note ------------------------------------------------------ #
    story.append(Paragraph("Scope and Limitations", h2))
    story.append(Paragraph(
        "This report reflects a fragile watermark keyed to the supplied password. "
        "A verdict of AUTHENTIC confirms that every 8x8 block matches the tag "
        "embedded at the time of protection, and that no block has been moved from "
        "its original position. The scheme is intentionally not robust: any lossy "
        "re-encoding (JPEG), resizing, rotation, or cropping will invalidate the "
        "entire image and produce an UNVERIFIABLE verdict rather than a localised "
        "result. Protected images must be stored and transmitted as PNG. This "
        "report attests to bit-level integrity only; it makes no claim about "
        "whether the original scene was itself staged or misrepresented.", body))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return output_path


